import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('e2e-only-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL(url => !url.pathname.includes('/login'))
}

test('organizer publishes an event and a separate attendee session receives a persisted QR ticket', async ({ browser }) => {
  const ownerContext = await browser.newContext()
  const owner = await ownerContext.newPage()
  const errors: string[] = []
  owner.on('pageerror', error => errors.push(error.message))
  await login(owner, 'organizer@example.kz')
  await owner.goto('/organizer/events/new')
  await owner.getByLabel('Event title', { exact: true }).fill('Report 3 browser smoke event')
  await owner.getByLabel('Short summary', { exact: true }).fill('Created through the database-backed website')
  await owner.getByLabel('Venue name', { exact: true }).fill('University Hall')
  await owner.getByLabel('Address', { exact: true }).fill('Campus')
  await owner.getByRole('button', { name: 'Save draft', exact: true }).click()
  await owner.waitForURL(url => /^\/organizer\/events\/[a-f0-9-]+$/.test(url.pathname))
  const id = owner.url().split('/').at(-1)
  await owner.getByRole('button', { name: 'Publish', exact: true }).click()
  await expect(owner.getByRole('button', { name: 'Unpublish', exact: true })).toBeVisible()

  const attendeeContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await attendeeContext.addInitScript(() => Object.defineProperty(crypto, 'randomUUID', { value: undefined }))
  const attendee = await attendeeContext.newPage()
  attendee.on('pageerror', error => errors.push(error.message))
  await login(attendee, 'attendee@example.kz')
  await attendee.goto(`/events/${id}`)
  await attendee.getByRole('button', { name: 'Add one General Admission', exact: true }).click()
  await attendee.getByRole('button', { name: 'Continue with 1 ticket', exact: true }).click()
  await attendee.getByRole('button', { name: 'Get free tickets', exact: true }).click()
  await attendee.waitForURL('**/tickets?order=*')
  await expect(attendee.getByRole('heading', { name: 'My tickets', exact: true })).toBeVisible()
  await expect(attendee.getByText('Report 3 browser smoke event', { exact: true })).toBeVisible()
  await attendee.locator('a[href^="/tickets/"]').first().click()
  await expect(attendee.getByRole('button', { name: 'Print / PDF', exact: true })).toBeVisible()
  await expect(attendee.locator('svg[width="220"]')).toBeVisible()
  await attendee.reload()
  await expect(attendee.locator('svg[width="220"]')).toBeVisible()
  expect(await attendee.evaluate(() => localStorage.getItem('bf.mockdb'))).toBeNull()
  expect(errors).toEqual([])
  await ownerContext.close()
  await attendeeContext.close()
})

test('declined paid checkout stays on checkout; a campaign discount is validated and a successful purchase issues tickets', async ({ page, request }) => {
  await login(page, 'attendee@example.kz')
  const events = await (await request.get('/api/v1/events')).json()
  const paid = events.find((event: { title: string }) => event.title === 'Starpers paid demo')
  expect(paid).toBeTruthy()
  await page.goto(`/events/${paid.id}`)
  await page.getByRole('button', { name: /^Add one General admission$/i }).click()
  await page.getByRole('button', { name: 'Continue with 1 ticket', exact: true }).click()
  await page.getByLabel(/Test card.*0002/).check()
  await page.getByRole('button', { name: /^Pay / }).click()
  await expect(page.getByText('Payment declined', { exact: true })).toBeVisible()
  expect(new URL(page.url()).pathname).toContain('/checkout/')

  await page.goto(`/events/${paid.id}?promo=STUDENT20`)
  await expect(page.getByText(/STUDENT20 applied/)).toBeVisible()
  await page.getByRole('button', { name: /^Add one General admission$/i }).click()
  await page.getByRole('button', { name: 'Continue with 1 ticket', exact: true }).click()
  await expect(page.getByText('Promo STUDENT20', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^Pay / }).click()
  await page.waitForURL('**/tickets?order=*')
  await expect(page.getByRole('heading', { name: 'My tickets', exact: true })).toBeVisible()
})
